  CASE
    WHEN mp."id" IS NULL THEN '—'
    ELSE COALESCE(mp."key", '') || ' — ' || COALESCE(mp."name", '')
  END AS "maintenancePlanLabel",
  CASE
    WHEN ir."id" IS NULL THEN '—'

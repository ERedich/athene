  END AS "problemLabel",
  CASE
    WHEN c."id" IS NULL THEN '—'
    ELSE COALESCE(c."key", '') || ' — ' || COALESCE(c."name", '')
  END AS "causeLabel",
  CASE
    WHEN r."id" IS NULL THEN '—'
    ELSE COALESCE(r."key", '') || ' — ' || COALESCE(r."name", '')
  END AS "remedyLabel",
  CASE
    WHEN dbe."id" IS NULL THEN '—'
    ELSE COALESCE(dbe."key", '') || ' — ' || COALESCE(dbe."name", '')
  END AS "doneByLabel",
  COALESCE(wo."pauseRemark", '') AS "pauseRemark",
  CASE
    WHEN orig."id" IS NULL THEN '—'
    ELSE '#' || orig."orderNumber"::text || ' — ' || COALESCE(orig."name", '')

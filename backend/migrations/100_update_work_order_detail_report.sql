JOIN "site" s ON s."id" = wo."siteId"
LEFT JOIN "asset" a ON a."id" = wo."assetId"
LEFT JOIN "costCenter" cc ON cc."id" = wo."costCenterId"
LEFT JOIN "classification" clf ON clf."id" = wo."classificationId"
LEFT JOIN "workgroup" wg ON wg."id" = wo."workgroupId"
LEFT JOIN "workOrderType" wot ON wot."key" = wo."orderType" AND wot."siteId" = wo."siteId"
LEFT JOIN "problem" p ON p."id" = wo."problemId"
LEFT JOIN "cause" c ON c."id" = wo."causeId"
LEFT JOIN "remedy" r ON r."id" = wo."remedyId"
LEFT JOIN "employee" dbe ON dbe."id" = wo."doneBy"
LEFT JOIN "workOrder" orig ON orig."id" = wo."originalWo"
LEFT JOIN "maintenancePlan" mp ON mp."id" = wo."maintenancePlanId"
LEFT JOIN "inspectionRound" ir ON ir."id" = wo."inspectionRoundId"
LEFT JOIN "users" created_by ON created_by."id" = wo."createdBy"
LEFT JOIN "users" updated_by ON updated_by."id" = wo."updatedBy"
